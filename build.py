#!/usr/bin/env python3
"""Turn files dropped into content/ into site cards.

Drop files into content/research, content/models or content/decks, then run:
    python3 build.py
(The GitHub Action in .github/workflows runs this for you on every upload.)

Files that share a name are grouped into one card, e.g.
    content/models/Tesla DCF.xlsx      -> download
    content/models/Tesla DCF.pdf       -> "View summary" (opens in the site viewer)
    content/models/Tesla DCF.png       -> cover image
    content/models/Tesla DCF.txt       -> optional details (see below)

Optional details file (.txt), one "key: value" per line, all optional:
    title: Tesla DCF Valuation
    meta: DCF · Excel · 2026
    description: What I valued and the key finding.
    tags: DCF, Valuation, Autos
    highlights: Implied price = $215 | Upside = 12% | WACC = 8.5%
    links: Code = https://github.com/... | Article = https://...
    embed: https://docs.google.com/presentation/d/.../embed
    badge: My slides     (highlighted label shown at the top of the card)
    button: View my slides  (custom text for the view button)
    order: 1            (lower shows first; otherwise newest first)
    hide: yes           (keep it off the site)
Anything after a line with only "---" is ignored (handy for notes).
"""
import json, os, re, sys, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CONTENT = ROOT / "content"
CATEGORIES = ["research", "models", "decks"]
DOCS = {".pdf"}
DOWNLOADS = {".xlsx", ".xlsm", ".xls", ".csv", ".pptx", ".ppt", ".key", ".docx", ".zip"}
IMAGES = {".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif", ".svg"}
DETAILS = {".txt", ".md"}


def pretty_title(stem):
    t = re.sub(r"[_\-]+", " ", stem).strip()
    return t[:1].upper() + t[1:] if t else stem


def parse_details(path):
    out = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.strip() == "---":
            break
        m = re.match(r"\s*([A-Za-z]+)\s*:\s*(.*)$", line)
        if m:
            out[m.group(1).lower()] = m.group(2).strip()
    return out


def pairs(value):
    items = []
    for part in value.split("|"):
        if "=" in part:
            k, v = part.split("=", 1)
            items.append((k.strip(), v.strip()))
    return items


def rel(p):
    return p.relative_to(ROOT).as_posix()


def build():
    projects = []
    for cat in CATEGORIES:
        folder = CONTENT / cat
        if not folder.is_dir():
            continue
        groups = {}
        for f in sorted(folder.iterdir()):
            if f.is_file() and not f.name.startswith("."):
                groups.setdefault(f.stem, []).append(f)
        for stem, files in groups.items():
            by = {"doc": None, "download": None, "image": None, "details": None}
            for f in files:
                ext = f.suffix.lower()
                kind = ("doc" if ext in DOCS else "download" if ext in DOWNLOADS
                        else "image" if ext in IMAGES else "details" if ext in DETAILS else None)
                if kind and not by[kind]:
                    by[kind] = f
            d = parse_details(by["details"]) if by["details"] else {}
            if d.get("hide", "").lower() in ("yes", "true", "1"):
                continue
            if not (by["doc"] or by["download"] or d.get("embed") or d.get("links")):
                continue  # an image or note on its own isn't a project
            newest = max(f.stat().st_mtime for f in files)
            year = datetime.date.fromtimestamp(newest).year
            p = {
                "category": cat,
                "title": d.get("title") or pretty_title(stem),
                "meta": d.get("meta") or str(year),
                "description": d.get("description", ""),
                "tags": [t.strip() for t in d.get("tags", "").split(",") if t.strip()],
                "image": rel(by["image"]) if by["image"] else "",
                "pdf": rel(by["doc"]) if by["doc"] else "",
                "embed": d.get("embed", ""),
                "badge": d.get("badge", ""),
                "view_label": d.get("button", ""),
                "download": rel(by["download"]) if by["download"] else "",
                "links": [{"label": k, "url": v} for k, v in pairs(d.get("links", ""))],
                "_order": float(d["order"]) if re.fullmatch(r"-?\d+(\.\d+)?", d.get("order", "")) else None,
                "_mtime": newest,
            }
            hl = pairs(d.get("highlights", ""))
            if hl:
                p["highlights"] = [{"label": k, "value": v} for k, v in hl]
            projects.append(p)

    projects.sort(key=lambda p: (p["_order"] is None, p["_order"] or 0, -p["_mtime"]))
    for p in projects:
        p.pop("_order"); p.pop("_mtime")

    out = CONTENT / "projects.js"
    out.write_text(
        "// Generated by build.py from the files in content/. Don't edit by hand; re-run build.py.\n"
        "window.PROJECTS = " + json.dumps(projects, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    counts = {c: sum(p["category"] == c for p in projects) for c in CATEGORIES}
    print(f"Wrote {rel(out)}: {len(projects)} projects {counts}")


if __name__ == "__main__":
    build()
